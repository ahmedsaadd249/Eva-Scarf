-- Eva Scarf database (PostgreSQL / Supabase). Safe to run again: everything is IF NOT EXISTS.
-- Money columns are integer piasters (1 EGP = 100 piasters).

-- Delivery neighborhoods. A NULL fee means "not delivered to yet": hidden from customers.
CREATE TABLE IF NOT EXISTS zones (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_ar    text NOT NULL,
  city_en    text NOT NULL DEFAULT '',
  name_ar    text NOT NULL,
  name_en    text NOT NULL DEFAULT '',
  fee        integer CHECK (fee IS NULL OR fee >= 0),
  sort_order integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS users (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email           text NOT NULL UNIQUE,            -- always stored lower-case
  password_hash   text NOT NULL,
  full_name       text NOT NULL,
  role            text NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
  lang            text NOT NULL DEFAULT 'ar' CHECK (lang IN ('ar', 'en')),
  phone_primary   text,
  phone_secondary text,
  zone_id         integer REFERENCES zones(id) ON DELETE SET NULL,
  city            text,                            -- readable copies of the zone names
  village         text,
  street          text,
  building_no     text,
  apartment_no    text,
  created_at      timestamptz NOT NULL DEFAULT now()
);

-- welcomed_at: when the welcome email went out (sent once, the first time the profile is saved).
-- Accounts that existed before this column was added already got theirs at sign-up.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_schema = current_schema() AND table_name = 'users' AND column_name = 'welcomed_at') THEN
    ALTER TABLE users ADD COLUMN welcomed_at timestamptz;
    UPDATE users SET welcomed_at = created_at;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS categories (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug       text NOT NULL UNIQUE,
  name_ar    text NOT NULL,
  name_en    text NOT NULL,
  image      text,
  sort_order integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS products (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug             text NOT NULL UNIQUE,
  name_ar          text NOT NULL DEFAULT '',
  name_en          text NOT NULL DEFAULT '',
  description_ar   text NOT NULL DEFAULT '',
  description_en   text NOT NULL DEFAULT '',
  category_id      integer REFERENCES categories(id) ON DELETE SET NULL,
  swatch           text NOT NULL DEFAULT '#E8339A',
  price            integer NOT NULL CHECK (price >= 0),
  discount_percent integer NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 90),
  stock            integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  is_featured      smallint NOT NULL DEFAULT 0,
  is_active        smallint NOT NULL DEFAULT 1,
  is_archived      smallint NOT NULL DEFAULT 0,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS product_images (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  path       text NOT NULL,                        -- /samples/…, /uploads/… or a Supabase Storage URL
  sort_order integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_product_images_product ON product_images(product_id, sort_order);

CREATE TABLE IF NOT EXISTS orders (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no        text UNIQUE,
  user_id         integer REFERENCES users(id) ON DELETE SET NULL,
  status          text NOT NULL DEFAULT 'processing' CHECK (status IN ('processing', 'shipped', 'delivered')),
  customer_name   text NOT NULL,
  customer_email  text NOT NULL,
  phone_primary   text NOT NULL,
  phone_secondary text,
  zone_id         integer REFERENCES zones(id) ON DELETE SET NULL,
  city            text NOT NULL,
  village         text NOT NULL,
  street          text NOT NULL,
  building_no     text NOT NULL,
  apartment_no    text NOT NULL,
  subtotal        integer NOT NULL,
  discount_total  integer NOT NULL,
  delivery_fee    integer NOT NULL,
  total           integer NOT NULL,
  payment_method  text NOT NULL DEFAULT 'cod',
  lang            text NOT NULL DEFAULT 'ar',
  rating_token    text UNIQUE,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);

CREATE TABLE IF NOT EXISTS order_items (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id         integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id       integer REFERENCES products(id) ON DELETE SET NULL,
  name_ar          text NOT NULL DEFAULT '',
  name_en          text NOT NULL DEFAULT '',
  image            text,
  swatch           text,
  unit_price       integer NOT NULL,
  discount_percent integer NOT NULL DEFAULT 0,
  final_unit_price integer NOT NULL,
  qty              integer NOT NULL CHECK (qty > 0),
  line_total       integer NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product ON order_items(product_id);

CREATE TABLE IF NOT EXISTS order_status_history (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status     text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ratings (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   integer NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
  stars      integer NOT NULL CHECK (stars BETWEEN 1 AND 5),
  comment    text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS settings (
  key   text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  sid     text PRIMARY KEY,
  sess    jsonb NOT NULL,
  expires bigint NOT NULL                          -- epoch milliseconds
);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires);

CREATE TABLE IF NOT EXISTS password_resets (
  token_hash text PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL,                      -- epoch milliseconds
  used       smallint NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS email_log (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_addr    text NOT NULL,
  type       text NOT NULL,
  status     text NOT NULL,
  error      text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Map location of the delivery address (optional): saved on the profile and copied onto each
-- order, so the courier can navigate and old orders keep the place they were sent to.
ALTER TABLE users  ADD COLUMN IF NOT EXISTS location_lat   double precision;
ALTER TABLE users  ADD COLUMN IF NOT EXISTS location_lng   double precision;
ALTER TABLE users  ADD COLUMN IF NOT EXISTS location_label text;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS location_lat   double precision;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS location_lng   double precision;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS location_label text;

-- Supabase exposes the "public" schema through its auto-generated REST API. This store never uses
-- that API (the server connects directly), so lock every table down: with row level security on and
-- no policies, the public/anon key can't read or change anything.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['zones','users','categories','products','product_images','orders','order_items',
                           'order_status_history','ratings','settings','sessions','password_resets','email_log'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
