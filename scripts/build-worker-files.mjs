// Bundles the files the store reads while running (page and email templates, translations, the email
// logo) into worker/files.generated.js. A Cloudflare Worker has no project folder to read them from,
// so worker/register.js hands this bundle to src/lib/platform.js instead.
// Runs before every `wrangler deploy` / `wrangler dev` (build.command in wrangler.jsonc).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TEXT = [['src/views', '.ejs'], ['src/emails', '.ejs'], ['src/locales', '.json']];
const BINARY = ['public/brand/email-monogram.png'];
export const OUTPUT = path.join(ROOT, 'worker', 'files.generated.js');

const posix = (p) => p.split(path.sep).join('/');

/** { text: { 'src/views/shop/home.ejs': '…' }, binary: { 'public/brand/…png': base64 } } */
export function collectFiles() {
  const text = {};
  for (const [dir, ext] of TEXT) {
    for (const name of fs.readdirSync(path.join(ROOT, dir), { recursive: true }).map(String).sort()) {
      if (name.endsWith(ext)) text[`${dir}/${posix(name)}`] = fs.readFileSync(path.join(ROOT, dir, name), 'utf8');
    }
  }
  const binary = Object.fromEntries(BINARY.map((rel) => [rel, fs.readFileSync(path.join(ROOT, rel)).toString('base64')]));
  return { text, binary };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const files = collectFiles();
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, '// Generated by scripts/build-worker-files.mjs; do not edit.\n'
    + `export default ${JSON.stringify(files)};\n`);
  console.log(`Bundled ${Object.keys(files.text).length} text files and ${Object.keys(files.binary).length} images for the Worker.`);
}
